"""渲染结果、渲染队列与调度落点清单的示例数据。

这些表由渲染结果业务单独维护，放在这里而不是塞进主 seed 文件里，
避免主示例数据跟着渲染规则一起膨胀。字段命名与接口保持一致，方便复核人员直接阅读。

三张表的关系：
- ``renderresult``：渲染结果（正文 / 快照引用 / 等待条件 / 版本线 / 诊断信息）。
- ``renderqueue``：队列状态（每个渲染作业只占一个位置，容量占用与回写情况）。
- ``renderlanding``：调度落点侧清单（读取队列状态、回写容量、接收结果快照）。
"""
from __future__ import annotations

from typing import Any


def _condition(name: str, met: bool, evidence: str, at: str | None) -> dict[str, Any]:
    return {"条件": name, "满足": met, "证据": evidence, "校验时间": at}


def _version(
    version: int,
    *,
    status: str,
    boundary: str,
    queue_boundary: str,
    reason: str,
    page_version: int,
    success: bool,
    at: str,
) -> dict[str, Any]:
    return {
        "结果版本": version,
        "状态": status,
        "结果边界": boundary,
        "排队边界": queue_boundary,
        "版本原因": reason,
        "页面版本": page_version,
        "成功页面": success,
        "生成时间": at,
    }


def _retry(
    retryable: bool,
    token: str,
    attempts: int,
    satisfied: list[str],
    unsatisfied: list[str],
    strategy: str,
    strategy_version: int,
    page_version: int,
    note: str,
    *,
    queue_code: str,
    job_code: str,
) -> dict[str, Any]:
    return {
        "可重试": retryable,
        "重试令牌": token,
        "已尝试次数": attempts,
        "保留条件": {
            "作业编号": job_code,
            "队列编号": queue_code,
            "已满足等待条件": list(satisfied),
            "未满足等待条件": list(unsatisfied),
            "等待策略": strategy,
            "等待策略版本": strategy_version,
            "页面版本": page_version,
        },
        "沿用等待策略": strategy,
        "等待策略版本": strategy_version,
        "页面版本": page_version,
        "说明": note,
    }


def _snapshot(
    ref: str,
    result_code: str,
    result_version: int,
    page_version: int,
    url: str,
    success: bool,
    deliverable: bool,
    digest: str,
    diagnostics: list[dict[str, Any]],
    at: str,
) -> dict[str, Any]:
    return {
        "快照引用": ref,
        "结果编号": result_code,
        "结果版本": result_version,
        "页面版本": page_version,
        "目标URL": url,
        "成功页面": success,
        "可交付": deliverable,
        "页面摘要": digest,
        "诊断摘要": [item["类型"] for item in diagnostics],
        "快照时间": at,
    }


